"""
Post-build email notification script for CSC418 Midterm (SP23-BAI-031).
Sends build & model metrics to evaluator upon successful deployment.
"""
import argparse
import json
import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from pathlib import Path

STUDENT_ID = "SP23-BAI-031"
DEFAULT_SENDER = "m.faiq.khan78@gmail.com"
EVALUATOR_EMAIL = "qasimalik@gmail.com"
TEST_EMAIL = "faiqkhanofficial786@gmail.com"
EC2_HOST = "3.110.121.46"
APP_PORT = "8000"


def load_metrics():
    path = Path("artifacts/metrics.json")
    if path.exists():
        try:
            return json.loads(path.read_text())
        except Exception:
            pass
    return {
        "student_id": STUDENT_ID,
        "accuracy": "N/A",
        "training_rows": "N/A",
        "model_version": "N/A",
        "dataset_sha256": "N/A",
        "git_sha": os.environ.get("GIT_COMMIT", "N/A"),
    }


def send_notification(to_email: str, test_mode: bool = False):
    sender = os.environ.get("SENDER_EMAIL", DEFAULT_SENDER)
    password = os.environ.get("GMAIL_APP_PASSWORD", "").strip()
    recipient = TEST_EMAIL if test_mode else (to_email or EVALUATOR_EMAIL)

    metrics = load_metrics()
    git_sha = os.environ.get("GIT_COMMIT", metrics.get("git_sha", "unknown"))
    build_num = os.environ.get("BUILD_NUMBER", "local")

    subject = f"[CSC418 Midterm] Deployment Notification - {STUDENT_ID}"

    body_text = f"""CSC418 DevOps Midterm Deployment Report
=============================================
Student ID      : {STUDENT_ID}
Build Number    : #{build_num}
Git Commit      : {git_sha}
Status          : SUCCESS

Model & Pipeline Metrics:
-------------------------
Accuracy        : {metrics.get('accuracy')}
Training Rows   : {metrics.get('training_rows')}
Model Version   : {metrics.get('model_version')}
Dataset SHA256  : {metrics.get('dataset_sha256')}

Deployed Application Endpoints (AWS EC2):
----------------------------------------
Base URL        : http://{EC2_HOST}:{APP_PORT}
Health Check    : http://{EC2_HOST}:{APP_PORT}/health
Metrics (GET)   : http://{EC2_HOST}:{APP_PORT}/metrics
Predict (POST)  : http://{EC2_HOST}:{APP_PORT}/predict

Sample POST /predict payload:
{{"records": [{{"basket_volatility": 0.5, "stock_gap": -0.2, "promotion_load": 0.8, "delivery_delay": 0.1}}]}}

This automated notification was generated by the Jenkins CI/CD pipeline on AWS EC2.
"""

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = recipient
    msg.attach(MIMEText(body_text, "plain"))

    print(f"Preparing to send notification email:")
    print(f"  From    : {sender}")
    print(f"  To      : {recipient}")
    print(f"  Subject : {subject}")

    if not password:
        print("\n[WARNING] GMAIL_APP_PASSWORD environment variable is not set!")
        print("To send the actual email, please set GMAIL_APP_PASSWORD with your 16-character Google App Password.")
        print("Generated email body would have been:")
        print("--------------------------------------------------")
        print(body_text)
        print("--------------------------------------------------")
        return False

    try:
        # First try port 587 with STARTTLS, fallback to port 465 SSL
        try:
            server = smtplib.SMTP("smtp.gmail.com", 587, timeout=20)
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(sender, password)
            server.sendmail(sender, [recipient], msg.as_string())
            server.quit()
            print(f"[SUCCESS] Email successfully sent to {recipient} via port 587 (STARTTLS)!")
            return True
        except Exception as e587:
            print(f"[INFO] Port 587 attempt failed ({e587}), trying port 465 (SSL)...")
            server = smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=20)
            server.ehlo()
            server.login(sender, password)
            server.sendmail(sender, [recipient], msg.as_string())
            server.quit()
            print(f"[SUCCESS] Email successfully sent to {recipient} via port 465 (SSL)!")
            return True
    except Exception as e:
        print(f"[ERROR] Failed to send email via SMTP: {e}")
        return False


def main():
    parser = argparse.ArgumentParser(description="Send post-build notification email.")
    parser.add_argument("--to", default=EVALUATOR_EMAIL, help="Recipient email address")
    parser.add_argument("--test", action="store_true", help=f"Send to test email ({TEST_EMAIL}) instead")
    args = parser.parse_args()

    send_notification(args.to, args.test)


if __name__ == "__main__":
    main()
